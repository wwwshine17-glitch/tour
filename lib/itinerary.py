DAYS_BY_TRIP_LENGTH = {"2박3일": 3, "3박4일": 4}


def generate_itinerary(destination: str, trip_length: str) -> list[dict]:
    """여행지의 일자별 코스를 생성한다. 여행지별로 준비된 서로 다른 활동
    세트를 날짜마다 돌려써서 일정이 겹치지 않게 한다. 실제 여행사 상품
    데이터가 연동되면 상품별 일정으로 대체될 수 있다."""
    variants = DESTINATION_DAY_VARIANTS.get(destination, DEFAULT_DAY_VARIANTS)
    n_days = DAYS_BY_TRIP_LENGTH.get(trip_length, 3)

    itinerary = []
    for day in range(1, n_days + 1):
        variant = variants[(day - 1) % len(variants)]
        if day == 1:
            plan = {"오전": "이동 및 숙소 체크인", "오후": variant["오후"], "저녁": variant["저녁"]}
        elif day == n_days:
            plan = {"오전": variant["오전"], "오후": "숙소 체크아웃 및 이동", "저녁": "귀가"}
        else:
            plan = dict(variant)
        itinerary.append({"day": day, **plan})
    return itinerary
