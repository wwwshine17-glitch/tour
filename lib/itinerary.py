DEFAULT_ACTIVITY = {"오전": "자유 일정", "오후": "지역 명소 탐방", "저녁": "현지 맛집에서 저녁"}

DAYS_BY_TRIP_LENGTH = {"2박3일": 3, "3박4일": 4}


def generate_itinerary(destination: str, trip_length: str) -> list[dict]:
    """여행지의 일자별 코스를 생성한다. 지금은 여행지별 실제 대표 명소를 고정
    배치한 mock 데이터이며, 실제 여행사 상품 데이터가 연동되면 상품별 일정으로
    대체될 수 있다."""
    activity = DESTINATION_ACTIVITIES.get(destination, DEFAULT_ACTIVITY)
    n_days = DAYS_BY_TRIP_LENGTH.get(trip_length, 3)

    itinerary = []
    for day in range(1, n_days + 1):
        if day == 1:
            plan = {"오전": "이동 및 숙소 체크인", "오후": activity["오후"], "저녁": activity["저녁"]}
        elif day == n_days:
            plan = {"오전": activity["오전"], "오후": "숙소 체크아웃 및 이동", "저녁": "귀가"}
        else:
            plan = dict(activity)
        itinerary.append({"day": day, **plan})
    return itinerary
